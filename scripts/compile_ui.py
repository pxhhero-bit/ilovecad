"""Compile every Qt Designer .ui file into a Python module with pyside6-uic.

Edit the .ui files (by hand or in pyside6-designer), then run this script.
Generated modules live in src/ilovecad/ui/generated/ and are gitignored.
"""
from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
UI_DIR = ROOT / "src" / "ilovecad" / "ui"
OUT_DIR = UI_DIR / "generated"


def uic_command() -> list[str]:
    exe = shutil.which("pyside6-uic")
    if exe:
        return [exe]
    # Fall back to the module entry point of the running interpreter.
    return [sys.executable, "-m", "PySide6.scripts.uic"]


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "__init__.py").write_text(
        "# SPDX-License-Identifier: GPL-3.0-or-later\n# generated by scripts/compile_ui.py\n",
        encoding="utf-8",
    )
    cmd = uic_command()
    ui_files = sorted(UI_DIR.glob("*.ui"))
    if not ui_files:
        print("No .ui files found")
        return 1
    ok = True
    for ui in ui_files:
        target = OUT_DIR / f"ui_{ui.stem}.py"
        result = subprocess.run(cmd + [str(ui), "-o", str(target)], capture_output=True, text=True)
        if result.returncode != 0:
            ok = False
            print(f"FAIL {ui.name}: {result.stderr.strip()[:600]}")
        else:
            print(f"OK   {ui.name} -> {target.name}")
    if not ok:
        print("Some .ui files failed to compile. Fix them in Qt Designer and retry.")
        return 1
    print("All UI files compiled. Restart IloveCAD to pick up changes.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
